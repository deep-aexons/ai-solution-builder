def test_settings_secret_key_and_database(built):
    backend = built[0] / "app/backend"
    env = {
        k: v
        for k, v in os.environ.items()
        if k not in ("DEBUG", "SECRET_KEY", "DATABASE_URL")
    }
    env["DJANGO_SETTINGS_MODULE"] = "config.settings"
    probe = "import config.settings"
    bad = subprocess.run(
        [sys.executable, "-c", probe],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert bad.returncode != 0
    assert "SECRET_KEY" in bad.stderr
    env.update(SECRET_KEY="k", DATABASE_URL="postgres://u:p%40w@db.example:5433/app")
    show = "import config.settings as s; print(s.DATABASES['default'])"
    ok = subprocess.run(
        [sys.executable, "-c", show],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert ok.returncode == 0, ok.stderr
    assert "'HOST': 'db.example'" in ok.stdout
    assert "'PORT': '5433'" in ok.stdout
    assert "'PASSWORD': 'p@w'" in ok.stdout


def _assert_golden(actual: str, golden: Path) -> None:
    if os.environ.get("UPDATE_GOLDEN") == "1":
        golden.write_text(actual, encoding="utf-8")
    assert actual == golden.read_text(encoding="utf-8")


