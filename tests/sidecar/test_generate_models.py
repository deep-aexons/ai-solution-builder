def test_failed_makemigrations_restores_old_migrations(tmp_path, monkeypatch):
    gen = sys.modules["asb_sidecar.generate"]

    generate(load_solution(FIXTURE), tmp_path)
    mig = next((tmp_path / "app/backend/entities/migrations").glob("0*.py"))
    before = mig.read_bytes()

    def boom(_backend):
        raise RuntimeError("makemigrations failed")

    monkeypatch.setattr(gen, "_makemigrations", boom)
    with pytest.raises(RuntimeError):
        generate(load_solution(FIXTURE), tmp_path)
    assert mig.read_bytes() == before
