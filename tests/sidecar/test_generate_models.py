def test_two_runs_are_byte_identical(tmp_path):
    sol = load_solution(ALL_TYPES)
    generate(sol, tmp_path)
    app = tmp_path / "app"
    snap = {p: p.read_bytes() for p in app.rglob("*") if p.is_file()}
    generate(sol, tmp_path)
    assert {p: p.read_bytes() for p in app.rglob("*") if p.is_file()} == snap
    migration = next((app / "backend/entities/migrations").glob("0*.py"))
    assert "# Generated by Django" not in migration.read_text(encoding="utf-8")


def _one_field(**field) -> Solution:
    base = _mini("T-{#}").model_dump(by_alias=True)
    base["entities"][0]["numbering"] = None
    base["entities"][0]["fields"] = [{"name": "title", "type": "text", **field}]
    return Solution.model_validate(base)


