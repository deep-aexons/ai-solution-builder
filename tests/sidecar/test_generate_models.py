"""Generated apps run only in subprocesses, never in the builder's pytest process."""

import datetime
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest
from asb_sidecar import generate

from asb.model import Solution, load_solution

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests" / "fixtures" / "gate_pass.yaml"
GOLDEN = Path(__file__).parent / "golden" / "models.py"
HEADER = "# GENERATED by asb — do not edit; regenerate from solution.yaml"


def _run(backend: Path, *args: str) -> subprocess.CompletedProcess:
    env = {k: v for k, v in os.environ.items() if k != "DATABASE_URL"}
    env.update(DJANGO_SETTINGS_MODULE="config.settings", DEBUG="1")
    return subprocess.run(
        [sys.executable, "manage.py", *args],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )


@pytest.fixture(scope="module")
def built(tmp_path_factory):
    sol_dir = tmp_path_factory.mktemp("sol")
    result = generate(load_solution(FIXTURE), sol_dir)
    return sol_dir, result


def test_models_match_golden(built):
    sol_dir, _ = built
    actual = (sol_dir / "app/backend/entities/models.py").read_text(encoding="utf-8")
    if os.environ.get("UPDATE_GOLDEN") == "1":
        GOLDEN.write_text(actual, encoding="utf-8")
    assert actual == GOLDEN.read_text(encoding="utf-8")


def test_layout_headers_and_manifest(built):
    sol_dir, result = built
    app = sol_dir / "app"
    backend = app / "backend"
    for rel in (
        "manage.py",
        "requirements.txt",
        "config/__init__.py",
        "config/settings.py",
        "config/urls.py",
        "config/wsgi.py",
        "entities/__init__.py",
        "entities/apps.py",
        "entities/models.py",
        "entities/admin.py",
        "entities/migrations/__init__.py",
    ):
        first = (backend / rel).read_text(encoding="utf-8").splitlines()[0]
        assert first == HEADER, rel
    migs = list((backend / "entities/migrations").glob("0*.py"))
    assert migs
    for m in migs:
        assert m.read_text(encoding="utf-8").splitlines()[0] == HEADER
    manifest = json.loads((app / ".asb-manifest.json").read_text())
    assert list(manifest) == sorted(manifest)
    assert "backend/entities/models.py" in manifest
    assert all(len(v) == 64 for v in manifest.values())
    assert set(result.written) == set(manifest) | {".asb-manifest.json"}
    assert result.skipped_ai_owned == []
    assert not (backend / "db.sqlite3").exists()


def test_migrations_up_to_date(built):
    backend = built[0] / "app/backend"
    proc = _run(backend, "makemigrations", "--check", "--dry-run")
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert _run(backend, "check").returncode == 0


def test_regenerate_is_stable(tmp_path):
    sol = load_solution(FIXTURE)
    generate(sol, tmp_path)
    first = (tmp_path / "app/backend/entities/models.py").read_bytes()
    result = generate(sol, tmp_path)
    assert (tmp_path / "app/backend/entities/models.py").read_bytes() == first
    assert len([w for w in result.written if "/migrations/0" in w]) == 1


def test_numbering_and_children(built):
    backend = built[0] / "app/backend"
    assert _run(backend, "migrate").returncode == 0
    code = (
        "from entities.models import GatePass, GatePassLine\n"
        "a = GatePass.objects.create(direction='outbound', vehicle_no='MH 12', driver='x')\n"
        "b = GatePass.objects.create(direction='inbound', vehicle_no='MH 13', driver='y')\n"
        "GatePassLine.objects.create(parent=a, item='bolt', quantity='2.5')\n"
        "print(a.number, b.number, a.state, a.lines.count())\n"
    )
    proc = _run(backend, "shell", "--no-imports", "-c", code)
    assert proc.returncode == 0, proc.stderr
    year = datetime.datetime.now(datetime.UTC).year
    assert proc.stdout.split() == [f"GP-{year}-0001", f"GP-{year}-0002", "draft", "1"]


def _mini(numbering: str) -> Solution:
    return Solution.model_validate(
        {
            "solution": "mini",
            "version": 1,
            "description": "d",
            "entities": [
                {
                    "name": "ticket",
                    "label": "Ticket",
                    "numbering": numbering,
                    "fields": [{"name": "title", "type": "text", "required": True}],
                }
            ],
            "roles": {},
            "acceptance_tests": [],
        }
    )


def test_brace_numbering_pads_to_five(tmp_path):
    generate(_mini("GP-{YYYY}-{#####}"), tmp_path)
    backend = tmp_path / "app/backend"
    assert _run(backend, "migrate").returncode == 0
    code = (
        "from entities.models import Ticket\n"
        "print(Ticket.objects.create(title='a').number, Ticket.objects.create(title='b').number)\n"
    )
    proc = _run(backend, "shell", "--no-imports", "-c", code)
    year = datetime.datetime.now(datetime.UTC).year
    assert proc.stdout.split() == [f"GP-{year}-00001", f"GP-{year}-00002"], proc.stderr


def test_numbering_without_counter_rejected(tmp_path):
    with pytest.raises(ValueError, match="counter"):
        generate(_mini("GP-{YYYY}"), tmp_path)


def test_settings_secret_key_and_database(built):
    backend = built[0] / "app/backend"
    env = {
        k: v
        for k, v in os.environ.items()
        if k not in ("DEBUG", "SECRET_KEY", "DATABASE_URL")
    }
    env["DJANGO_SETTINGS_MODULE"] = "config.settings"
    probe = "import config.settings"
    bad = subprocess.run(
        [sys.executable, "-c", probe],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert bad.returncode != 0
    assert "SECRET_KEY" in bad.stderr
    env.update(SECRET_KEY="k", DATABASE_URL="postgres://u:p%40w@db.example:5433/app")
    show = "import config.settings as s; print(s.DATABASES['default'])"
    ok = subprocess.run(
        [sys.executable, "-c", show],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert ok.returncode == 0, ok.stderr
    assert "'HOST': 'db.example'" in ok.stdout
    assert "'PORT': '5433'" in ok.stdout
    assert "'PASSWORD': 'p@w'" in ok.stdout
