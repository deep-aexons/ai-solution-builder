def test_numbering_and_children(migrated):
    code = (
        "from entities.models import GatePass, GatePassLine\n"
        "a = GatePass.objects.create(direction='outbound', vehicle_no='MH 12', driver='x')\n"
        "b = GatePass.objects.create(direction='inbound', vehicle_no='MH 13', driver='y')\n"
        "GatePassLine.objects.create(parent=a, item='bolt', quantity='2.5')\n"
        "print(a.number, b.number, a.state, a.lines.count())\n"
    )
    proc = _run(migrated, "shell", "--no-imports", "-c", code)
    assert proc.returncode == 0, proc.stderr
    year = datetime.datetime.now(datetime.UTC).year
    assert proc.stdout.split() == [f"GP-{year}-00001", f"GP-{year}-00002", "draft", "1"]


def test_numbering_concurrent_sqlite(migrated):
    code = (
        "from entities.models import GatePass\n"
        "for i in range(10):\n"
        "    print(GatePass.objects.create(direction='outbound', vehicle_no='A', driver='d').number)\n"
    )
    procs = [
        subprocess.Popen(
            [sys.executable, "manage.py", "shell", "--no-imports", "-c", code],
            cwd=migrated,
            env=_env(),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        for _ in range(4)
    ]
    numbers: list[str] = []
    for p in procs:
        out, err = p.communicate(timeout=120)
        assert p.returncode == 0, err
        numbers += out.split()
    assert len(numbers) == 40
    assert len(set(numbers)) == 40


def test_numbering_restarts_each_year(tmp_path):
    generate(_mini("GP-{YYYY}-{#####}"), tmp_path)
    backend = tmp_path / "app/backend"
    assert _run(backend, "migrate").returncode == 0
    code = (
        "import datetime\n"
        "from unittest import mock\n"
        "from django.utils import timezone\n"
        "from entities.models import Ticket\n"
        "def at(y):\n"
        "    return mock.patch.object(timezone, 'now', lambda: datetime.datetime(y, 6, 1, tzinfo=datetime.UTC))\n"
        "with at(2030):\n"
        "    print(Ticket.objects.create(title='a').number, Ticket.objects.create(title='b').number)\n"
        "with at(2031):\n"
        "    print(Ticket.objects.create(title='c').number)\n"
    )
    proc = _run(backend, "shell", "--no-imports", "-c", code)
    assert proc.returncode == 0, proc.stderr
    assert proc.stdout.split() == ["GP-2030-00001", "GP-2030-00002", "GP-2031-00001"]


def _mini(numbering: str) -> Solution:
    return Solution.model_validate(
        {
            "solution": "mini",
            "version": 1,
            "description": "d",
            "entities": [
                {
                    "name": "ticket",
                    "label": "Ticket",
                    "numbering": numbering,
                    "fields": [{"name": "title", "type": "text", "required": True}],
                }
            ],
            "roles": {},
            "acceptance_tests": [],
        }
    )


