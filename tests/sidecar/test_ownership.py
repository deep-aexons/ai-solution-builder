def test_new_rule_gets_a_stub_existing_ones_stay(built):
    tmp, _ = built
    backend = tmp / "app/backend"
    (backend / "rules/r1.py").write_text("# mine\n")
    data = yaml.safe_load(FIXTURE.read_text(encoding="utf-8"))
    data["rules"].append({"id": "R3", "text": "A new rule."})
    generate(Solution.model_validate(data), tmp)
