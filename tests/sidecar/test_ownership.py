def test_stubs_are_ai_owned_files(built):
    tmp, result = built
    backend = tmp / "app/backend"
    manifest = json.loads((tmp / "app/.asb-manifest.json").read_text())
    for rel in (
        "rules/r1.py",
        "rules/r2.py",
        "reports/gate_register.py",
        *(f"tests/test_at_0{n}.py" for n in range(1, 7)),
    ):
        text = (backend / rel).read_text(encoding="utf-8")
        assert not text.startswith("# GENERATED"), rel
        assert f"backend/{rel}" not in manifest
        assert f"backend/{rel}" not in result.written
    assert 'raise NotImplementedError("R1 not implemented")' in (
        backend / "rules/r1.py"
    ).read_text(encoding="utf-8")
    assert "def run(filters: dict) -> list[dict]:" in (
        backend / "reports/gate_register.py"
    ).read_text(encoding="utf-8")
    at = (backend / "tests/test_at_01.py").read_text(encoding="utf-8")
    assert '@pytest.mark.at("AT-01")' in at
    assert 'pytest.fail("AT-01 not implemented")' in at
    assert result.skipped_ai_owned == []


