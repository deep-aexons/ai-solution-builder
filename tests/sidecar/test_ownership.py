def test_regenerate_keeps_ai_edits_and_is_byte_identical(built):
    tmp, _ = built
    backend = tmp / "app/backend"
    (backend / "rules/r1.py").write_text("def check(obj, erp):\n    return None\n")
    (backend / "reports/gate_register.py").write_text(
        "def run(filters):\n    return []\n"
    )
    (backend / "tests/test_at_02.py").write_text("# mine\n")
    (backend / "rules/_helpers.py").write_text("# mine too\n")
    before = _snapshot(tmp / "app")
    result = generate(load_solution(FIXTURE), tmp)
    assert _snapshot(tmp / "app") == before
    assert sorted(result.skipped_ai_owned) == sorted(
        [
            "backend/rules/r1.py",
            "backend/rules/r2.py",
            "backend/reports/gate_register.py",
            *(f"backend/tests/test_at_0{n}.py" for n in range(1, 7)),
        ]
    )
    assert not any(
        w.startswith(("backend/rules/r", "backend/tests/test_at"))
        for w in result.written
    )
    assert (
        backend / "rules/r1.py"
    ).read_text() == "def check(obj, erp):\n    return None\n"


