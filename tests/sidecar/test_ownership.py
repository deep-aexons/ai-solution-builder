def _env(**extra) -> dict[str, str]:
    env = {k: v for k, v in os.environ.items() if k != "DATABASE_URL"}
    env.update(
        DJANGO_SETTINGS_MODULE="config.settings", DEBUG="1", PYTHONDONTWRITEBYTECODE="1"
    )
    env.update(extra)
    return env


def test_connector_is_vendored_verbatim_and_listed_in_manifest(with_connector):
    _root, sol_dir = with_connector
    result = generate(
        load_solution(FIXTURE), sol_dir
    )  # root defaults to sol_dir.parents[1]
    backend = sol_dir / "app/backend"
    manifest = json.loads((sol_dir / "app/.asb-manifest.json").read_text())
    source = ROOT / "connectors/erpnext/asb_erpnext"
    vendored = sorted(
        p.relative_to(backend / "vendor/asb_erpnext").as_posix()
        for p in (backend / "vendor/asb_erpnext").rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    )
    assert vendored == sorted(
        p.relative_to(source).as_posix()
        for p in source.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    )
    for rel in vendored:
        assert (backend / "vendor/asb_erpnext" / rel).read_bytes() == (
            source / rel
        ).read_bytes()
        assert f"backend/vendor/asb_erpnext/{rel}" in manifest
    assert (backend / "vendor/asb/__init__.py").read_bytes() == b""
    contract = (backend / "vendor/asb/connector.py").read_bytes()
    assert contract == (ROOT / "core/tool/asb/connector.py").read_bytes()
    assert (
        manifest["backend/vendor/asb/connector.py"]
        == hashlib.sha256(contract).hexdigest()
    )
    assert "backend/vendor/asb/connector.py" in result.written
    assert not contract.startswith(b"# GENERATED")


