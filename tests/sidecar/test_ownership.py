def _shell(backend: Path, code: str, **env) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "manage.py", "shell", "-c", code],
        cwd=backend,
        env=_env(**env),
        capture_output=True,
        text=True,
        check=False,
    )


def test_get_connector_builds_cached_erpnext_connector(with_connector):
    _, sol_dir = with_connector
    data = yaml.safe_load(FIXTURE.read_text(encoding="utf-8"))
    data["external"][0]["access"] = "write:delivery_note"
    generate(Solution.model_validate(data), sol_dir)
    backend = sol_dir / "app/backend"
    code = (
        "import erp\n"
        "a = erp.get_connector(); b = erp.get_connector()\n"
        "print(type(a).__name__, a is b, sorted(a.allowed_writes))\n"
        "erp.reset_connector()\n"
        "print(erp.get_connector() is a)\n"
    )
    proc = _shell(
        backend,
        code,
        ASB_ERP_URL="http://erp.invalid",
        ASB_ERP_API_KEY="k",
        ASB_ERP_API_SECRET="s",
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert proc.stdout.splitlines()[-2:] == [
        "ERPNextConnector True ['write:outbound_shipment']",
        "False",
    ]


def test_get_connector_reports_missing_credentials_and_missing_connector(
    with_connector, tmp_path
):
    _, sol_dir = with_connector
    generate(load_solution(FIXTURE), sol_dir)
    env = {"ASB_ERP_URL": "", "ASB_ERP_API_KEY": "", "ASB_ERP_API_SECRET": ""}
    code = "import erp\ntry:\n    erp.get_connector()\nexcept Exception as e:\n    print(type(e).__name__, e)\n"
    proc = _shell(sol_dir / "app/backend", code, **env)
    assert "ConnectorError missing environment variable ASB_ERP_URL" in proc.stdout, (
        proc.stderr
    )
    generate(load_solution(FIXTURE), tmp_path)
    proc = _shell(tmp_path / "app/backend", code)
    assert "ConnectorError no connector configured" in proc.stdout, proc.stderr
