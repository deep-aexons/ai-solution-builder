def test_every_generated_frontend_file_has_its_header(app):
    manifest = _manifest(app)
    files = [rel for rel in manifest if rel.startswith("frontend/")]
    assert files
    for rel in files:
        text = (app / rel).read_text(encoding="utf-8")
        lines = text.splitlines()
        suffix = Path(rel).suffix
        name = Path(rel).name
        if suffix == ".json":
            assert "GENERATED" not in text, rel
            json.loads(text)
        elif suffix in (".ts", ".tsx", ".js"):
            assert lines[0] == SLASH, rel
        elif suffix == ".css":
            assert lines[0] == BLOCK, rel
        elif suffix == ".html":
            assert lines[0].lower() == "<!doctype html>", rel
            assert lines[1] == HTML, rel
        elif name == ".gitignore":
            assert lines[0] == HASH, rel
        else:
            pytest.fail(f"unexpected frontend file {rel}")
    for rel in ("Dockerfile", "docker-compose.yml", ".env.example", ".dockerignore"):
        assert (app / rel).read_text(encoding="utf-8").splitlines()[0] == HASH, rel
    assert (app / "README.md").read_text(encoding="utf-8").startswith(HTML)


