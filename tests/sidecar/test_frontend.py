@pytest.mark.slow
def test_frontend_builds(app, tmp_path):
    npm = shutil.which("npm")
    if not npm:
        pytest.skip("npm is not installed")
    try:
        ping = subprocess.run(
            [npm, "view", "react@18.3.1", "version"],
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
    except subprocess.TimeoutExpired:
        pytest.skip("npm registry unreachable (timeout)")
    if ping.returncode != 0:
        pytest.skip("npm registry unreachable: " + ping.stderr.strip()[:200])
    work = tmp_path / "frontend"
    shutil.copytree(app / "frontend", work)
    for cmd in (
        [npm, "install", "--no-audit", "--no-fund"],
        [npm, "run", "build"],
    ):
        proc = subprocess.run(
            cmd, cwd=work, capture_output=True, text=True, timeout=600, check=False
        )
        assert proc.returncode == 0, f"{cmd}\n{proc.stdout}\n{proc.stderr}"
    index = (work / "dist/index.html").read_text(encoding="utf-8")
    assert "/static/assets/" in index
    assert list((work / "dist/assets").glob("*.js"))


