_SPA_CHECK = textwrap.dedent(
    """
    import json, django
    django.setup()
    from django.test import Client
    c = Client()
    out = {}
    def body(r):
        return b"".join(r.streaming_content) if r.streaming else r.content
    for url in ("/", "/e/gate_pass/12", "/r/gate_register", "/api/meta/",
                "/api/nope/", "/admin", "/admin/login/", "/static/assets/app.js",
                "/static/assets/missing.js"):
        r = c.get(url)
        out[url] = [r.status_code, r["Content-Type"], body(r)[:200].decode("utf-8", "replace"),
                    r.get("Location", "")]
    r = c.post("/e/gate_pass/12", {})
    out["POST /e/"] = [r.status_code]
    print("RESULT" + json.dumps(out))
    """
)


def _spa(backend: Path) -> dict:
    env = {k: v for k, v in os.environ.items() if k != "DATABASE_URL"}
    env.update(
        DJANGO_SETTINGS_MODULE="config.settings",
        DEBUG="1",
        ALLOWED_HOSTS="testserver",
        PYTHONDONTWRITEBYTECODE="1",
    )
    proc = subprocess.run(
        [sys.executable, "-c", _SPA_CHECK],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    line = next(ln for ln in proc.stdout.splitlines() if ln.startswith("RESULT"))
    return json.loads(line[len("RESULT") :])


def test_django_serves_the_spa_for_non_api_paths(tmp_path):
    generate(load_solution(FIXTURE), tmp_path)
    backend = tmp_path / "app/backend"

    missing = _spa(backend)  # no dist yet
    assert missing["/"][0] == 404
    assert "Frontend not built" in missing["/"][2]
    assert "json" in missing["/"][1]

    dist = tmp_path / "app/frontend/dist"
    (dist / "assets").mkdir(parents=True)
    (dist / "index.html").write_text("<!doctype html><p>FAKE-SPA</p>", encoding="utf-8")
    (dist / "assets/app.js").write_text("console.log(1)", encoding="utf-8")
    seen = _spa(backend)
    for url in ("/", "/e/gate_pass/12", "/r/gate_register"):
        assert seen[url][0] == 200, url
        assert "FAKE-SPA" in seen[url][2], url
        assert seen[url][1].startswith("text/html"), url
    # API paths are not shadowed by the catch-all.
    assert seen["/api/meta/"][0] == 403
    assert "json" in seen["/api/meta/"][1]
    assert "FAKE-SPA" not in seen["/api/nope/"][2]
    assert seen["/api/nope/"][0] == 404
    # Admin keeps its own routing (APPEND_SLASH redirect, login page).
    assert seen["/admin"][0] == 301 and seen["/admin"][3].endswith("/admin/")
    assert seen["/admin/login/"][0] == 200
    assert "FAKE-SPA" not in seen["/admin/login/"][2]
    # Built assets come from static files, not index.html.
    assert seen["/static/assets/app.js"][0] == 200
    assert "console.log" in seen["/static/assets/app.js"][2]
    assert seen["/static/assets/missing.js"][0] == 404
    assert seen["POST /e/"][0] == 405


@pytest.mark.compose
@pytest.mark.skipif(
    os.environ.get("ASB_COMPOSE") != "1",
    reason="set ASB_COMPOSE=1 (needs Docker Compose)",
)
def test_compose_stack_serves_the_ui(app, tmp_path):
    work = tmp_path / "app"
    shutil.copytree(app, work)
    (work / ".env").write_text("SECRET_KEY=compose-test-key\n", encoding="utf-8")
    subprocess.run(["docker", "compose", "up", "--build", "-d"], cwd=work, check=True)
    try:
        import time

        import httpx

        deadline = time.time() + 120
        while True:
            try:
                resp = httpx.get("http://localhost:8000/", timeout=5)
                if resp.status_code == 200:
                    break
            except httpx.HTTPError:
                pass
            assert time.time() < deadline, "app did not come up"
            time.sleep(2)
        assert '<div id="root">' in resp.text
        assert httpx.get("http://localhost:8000/api/meta/").status_code == 403
    finally:
        subprocess.run(["docker", "compose", "down", "-v"], cwd=work, check=False)
