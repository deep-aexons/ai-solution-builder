def test_load_policy_merges_pack_without_removing_core(tmp_path):
    core = load_policy(tmp_path, None)
    assert set(core["checks"]) >= {"EVAL", "RAW_SQL", "SECRET", "HEADER_TAMPERED"}
    assert any("git" in p for p in core["deny_commands"])
    assert "no_permission" not in core
    pack = tmp_path / "packs" / "p"
    pack.mkdir(parents=True)
    (pack / "policy.yaml").write_text(
        "deny_commands: ['\\bshutdown\\b']\nskip_paths: [vendor/**]\n"
        "checks: []\nno_permission: {base_classes: [V], attribute: perms}\n",
        encoding="utf-8",
    )
    merged = load_policy(tmp_path, "p")
    assert set(core["deny_commands"]) <= set(merged["deny_commands"])
    assert "\\bshutdown\\b" in merged["deny_commands"]
    assert set(core["checks"]) == set(merged["checks"])
    assert set(core["skip_paths"]) < set(merged["skip_paths"])
    assert merged["no_permission"]["attribute"] == "perms"


