def _generated(tmp_path: Path) -> Path:
    body = f"{HEADER}\nx = 1\n"
    app_dir = _app(tmp_path, {"g.py": body, "h/i.py": body, "own.py": "y = 2\n"})
    manifest = {
        rel: hashlib.sha256((app_dir / rel).read_bytes()).hexdigest()
        for rel in ("g.py", "h/i.py")
    }
    (app_dir / ".asb-manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    return app_dir


def test_manifest_intact_is_clean(tmp_path):
    assert run_checks(_generated(tmp_path), POLICY) == []


def test_manifest_edited_missing_and_unknown(tmp_path):
    app_dir = _generated(tmp_path)
    (app_dir / "g.py").write_text(f"{HEADER}\nx = 2\n", encoding="utf-8")
    (app_dir / "h" / "i.py").unlink()
    (app_dir / "own.py").write_text(f"{HEADER}\nz = 3\n", encoding="utf-8")
    issues = run_checks(app_dir, POLICY)
    got = {
        (i.path, i.message.split()[0].rstrip(":"))
        for i in issues
        if i.code == "HEADER_TAMPERED"
    }
    assert got == {("g.py", "edited"), ("h/i.py", "missing"), ("own.py", "unknown")}


