def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _app(tmp_path: Path, files: dict[str, str], listed: tuple[str, ...] = ()) -> Path:
    """An app dir with a manifest listing the `listed` files at their current hash."""
    app_dir = tmp_path / "app"
    for rel, text in files.items():
        p = app_dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    app_dir.mkdir(exist_ok=True)
    manifest = {rel: _sha(app_dir / rel) for rel in listed}
    (app_dir / ".asb-manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    return app_dir


def _codes(app_dir: Path, policy: dict = POLICY) -> list[tuple[str, str]]:
    return [(i.code, i.path) for i in run_checks(app_dir, policy)]


