def _solution_with_app(tmp_path: Path, files: dict[str, str]) -> None:
    sol = new_solution(tmp_path, "demo", "sidecar-django", None)
    pack = tmp_path / "packs" / "sidecar-django"
    pack.mkdir(parents=True)
    (pack / "policy.yaml").write_text("skip_paths: []\n", encoding="utf-8")
    for rel, text in files.items():
        p = sol / "app" / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    (sol / "app" / ".asb-manifest.json").write_text("{}", encoding="utf-8")


