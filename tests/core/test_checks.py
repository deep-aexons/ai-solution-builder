def test_raw_sql_formatting(tmp_path):
    src = (
        "def f(cur, x, M):\n"
        '    cur.execute(f"select {x}")\n'
        '    cur.execute("select %s" % x)\n'
        '    M.objects.raw("select " + x)\n'
        '    cur.execute("select {}".format(x))\n'
        '    M.objects.extra("a " + x)\n'
    )
    ok = (
        "def g(cur, x, M):\n"
        '    cur.execute("select %s", [x])\n'
        '    M.objects.raw("select 1")\n'
        '    cur.execute(f"select 1")\n'
        '    cur.execute("select " + "1")\n'
    )
    app_dir = _app(tmp_path, {"bad.py": src, "ok.py": ok})
    assert _codes(app_dir) == [("RAW_SQL", "bad.py")] * 5


