def test_cli_use_sets_and_clears_active(tmp_path):
    new_solution(tmp_path, "one", "p", None)
    new_solution(tmp_path, "two", "p", None)
    active = tmp_path / ".asb" / "active"
    assert active.read_text().strip() == "two"  # asb new activates
    runner = CliRunner()
    assert runner.invoke(app, ["use", "one", "--root", str(tmp_path)]).exit_code == 0
    assert active.read_text().strip() == "one"
    assert runner.invoke(app, ["use", "nope", "--root", str(tmp_path)]).exit_code == 1
    assert active.read_text().strip() == "one"
    assert (
        runner.invoke(app, ["use", "--clear", "--root", str(tmp_path)]).exit_code == 0
    )
    assert not active.exists()
    assert runner.invoke(app, ["use", "--root", str(tmp_path)]).exit_code == 1


