_NUMBER_TOKEN = re.compile(r"\{YYYY\}|\{(#+)\}")


def _py(value: Any) -> str:
    """Python source for a literal; strings are double-quoted."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def _label(value: str) -> str:
    return value.replace("_", " ").capitalize()


def _choices(options: list[str]) -> str:
    return "[" + ", ".join(f"({_py(o)}, {_py(_label(o))})" for o in options) + "]"


def _number(value: float, decimal: bool) -> str:
    if decimal:
        return f"Decimal({_py(str(value))})"
    return repr(int(value) if float(value).is_integer() else value)


def _numbering_format(pattern: str, entity: str) -> str:
    """Translate '{YYYY}'/'{#####}' into a str.format string."""
    out: list[str] = []
    pos = 0
    counters = 0
    for m in _NUMBER_TOKEN.finditer(pattern):
        out.append(pattern[pos : m.start()].replace("{", "{{").replace("}", "}}"))
        hashes = m.group(1)
        if hashes:
            out.append(f"{{seq:0{len(hashes)}d}}")
            counters += 1
        else:
            out.append("{year}")
        pos = m.end()
    out.append(pattern[pos:].replace("{", "{{").replace("}", "}}"))
    if counters != 1:
        raise ValueError(
            f"entity '{entity}': numbering '{pattern}' needs exactly one counter token"
        )
    return "".join(out)


def _field_lines(entity: Entity, f: Field, long_text: bool) -> list[str]:
    name = f.name
    kw: list[str] = []
    validators: list[str] = []
    optional = not f.required

    def common(null_ok: bool) -> list[str]:
        extra = []
        if f.unique:
            extra.append("unique=True")
        return extra + (["null=True", "blank=True"] if optional and null_ok else [])

    def default_kw(null_ok: bool = True) -> list[str]:
        if f.default is not None:
            return [f"default={_py(f.default)}"]
        if optional and not null_ok and not f.unique:
            return ['default=""']
        return []

    def with_validators(extra: list[str]) -> list[str]:
        if f.pattern:
            validators.append(f"RegexValidator({_py(f.pattern)})")
        dec = f.type in ("decimal", "money")
        if f.min is not None:
            validators.append(f"MinValueValidator({_number(f.min, dec)})")
        if f.max is not None:
            validators.append(f"MaxValueValidator({_number(f.max, dec)})")
        if validators:
            extra.append("validators=[" + ", ".join(validators) + "]")
        return extra

    t = f.type
    uniq_null = optional and f.unique  # NULLs do not collide under a unique constraint
    if t == "table":
        return []
    if t == "text":
        if long_text:
            kw = (
                (["null=True", "blank=True"] if uniq_null else ["blank=True"])
                if optional
                else []
            )
            kw += default_kw(False)
            kw += ["unique=True"] if f.unique else []
            return [f"{name} = models.TextField({', '.join(with_validators(kw))})"]
        kw = (
            ["max_length=255"]
            + (
                (["null=True", "blank=True"] if uniq_null else ["blank=True"])
                if optional
                else []
            )
            + default_kw(False)
        )
        if f.unique:
            kw.append("unique=True")
        return [f"{name} = models.CharField({', '.join(with_validators(kw))})"]
    if t == "choice":
        if not f.options:
            raise ValueError(f"{entity.name}.{name}: choice field needs options")
        kw = ["max_length=64", f"choices={_choices(f.options)}"]
        if optional:
            kw += ["null=True", "blank=True"] if uniq_null else ["blank=True"]
        kw += default_kw(False)
        if f.unique:
            kw.append("unique=True")
        return [f"{name} = models.CharField({', '.join(kw)})"]
    if t == "external_ref":
        if not f.to:
            raise ValueError(f"{entity.name}.{name}: external_ref needs 'to'")
        blank = ["blank=True", 'default=""'] if optional else []
        return [
            f"{name}_kind = models.CharField(max_length=64, choices={_choices(f.to)}"
            + "".join(", " + b for b in blank)
            + ")",
            f"{name}_id = models.CharField(max_length=140"
            + "".join(", " + b for b in blank)
            + ")",
        ]
    if t == "link":
        if not f.to:
            raise ValueError(f"{entity.name}.{name}: link needs 'to'")
        kw = [f'"{_cls(f.to[0])}"', "on_delete=models.PROTECT", 'related_name="+"']
        kw += common(True)
        return [f"{name} = models.ForeignKey({', '.join(kw)})"]
    simple = {
        "number": "IntegerField",
        "date": "DateField",
        "datetime": "DateTimeField",
        "boolean": "BooleanField",
        "attachment": "FileField",
    }
    if t in simple:
        kw = []
        if t == "attachment":
            kw.append('upload_to="uploads/"')
        if t == "datetime" and f.default == "now":
            kw.append("default=timezone.now")
        elif t == "boolean" and optional and f.default is None:
            kw.append("default=False")
        elif f.default is not None:
            kw.append(f"default={_py(f.default)}")
        kw += common(t != "boolean")
        return [f"{name} = models.{simple[t]}({', '.join(with_validators(kw))})"]
    # decimal / money
    places = 6 if t == "decimal" else 2
    kw = [f"max_digits=18, decimal_places={places}"]
    if f.default is not None:
        kw.append(f"default=Decimal({_py(str(f.default))})")
    kw += common(True)
    return [f"{name} = models.DecimalField({', '.join(with_validators(kw))})"]


def _check_name(name: str, where: str) -> None:
    if keyword.iskeyword(name) or name in _RESERVED:
        raise ValueError(f"{where}: name '{name}' is reserved")


def _entity_context(solution: Solution, e: Entity) -> dict[str, Any]:
    ext = solution.extensions.get("sidecar-django") or {}
    long_text = bool(ext.get("long_text"))
    _check_name(e.name, "entity")
    if _cls(e.name) in _MODULE_NAMES:
        raise ValueError(f"entity '{e.name}': class name collides with generated code")
    for f in e.fields:
        if (f.min is not None or f.max is not None) and f.type not in (
            "number",
            "decimal",
            "money",
        ):
            raise ValueError(
                f"{e.name}.{f.name}: min/max only apply to number, decimal, money"
            )
        names = (
            [f.name, f"{f.name}_kind", f"{f.name}_id"]
            if f.type == "external_ref"
            else [f.name]
        )
        for n in names:
            _check_name(n, f"{e.name}.{f.name}")
    lines: list[str] = []
    workflow = next((w for w in solution.workflows if w.entity == e.name), None)
    if e.child_of:
        parent = next((p for p in solution.entities if p.name == e.child_of), None)
        if parent is None:
            raise ValueError(f"{e.name}: child_of '{e.child_of}' is not an entity")
        table = next(
            (f for f in parent.fields if f.type == "table" and f.of == e.name), None
        )
        rel = f', related_name="{table.name}"' if table else ""
        lines.append(
            f'parent = models.ForeignKey("{_cls(parent.name)}", on_delete=models.CASCADE{rel})'
        )
    for f in e.fields:
        lines += _field_lines(e, f, long_text)
    numbering = None
    if e.numbering:
        lines.insert(
            0, "number = models.CharField(max_length=64, unique=True, editable=False)"
        )
        numbering = _numbering_format(e.numbering, e.name)
    if workflow:
        lines.append(
            f"state = models.CharField(max_length=40, choices={_choices(workflow.states)}, "
            f"default={_py(workflow.initial)})"
        )
    if not e.child_of:
        lines += [
            (
                "created_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, "
                'blank=True, on_delete=models.PROTECT, related_name="+")'
            ),
            "created_at = models.DateTimeField(auto_now_add=True)",
            "modified_at = models.DateTimeField(auto_now=True)",
        ]
    return {
        "name": e.name,
        "cls": _cls(e.name),
        "label": e.label,
        "lines": lines,
        "numbering": numbering,
        "series_year": bool(numbering and "{year}" in numbering),
    }


def _env() -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(str(TEMPLATES)),
        undefined=jinja2.StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
        autoescape=False,
    )
    env.filters["pyrepr"] = _py
    return env


def _write(root: Path, rel: str, text: str, written: dict[str, bytes]) -> None:
    data = text.encode("utf-8")
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    written[rel] = data


def _makemigrations(backend: Path) -> None:
    env = {k: v for k, v in os.environ.items() if k != "DATABASE_URL"}
    env.update(
        DJANGO_SETTINGS_MODULE="config.settings",
        DEBUG="1",
        PYTHONDONTWRITEBYTECODE="1",
    )
    db = backend / "db.sqlite3"
    existed = db.exists()
    proc = subprocess.run(
        [sys.executable, "manage.py", "makemigrations", "entities"],
        cwd=backend,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if not existed and db.exists() and db.stat().st_size == 0:
        db.unlink()
    if proc.returncode != 0:
        raise RuntimeError(f"makemigrations failed:\n{proc.stdout}\n{proc.stderr}")


def generate(solution: Solution, solution_dir: Path) -> GenerateResult:
    app = Path(solution_dir) / "app"
    backend = app / "backend"
    env = _env()
    files: dict[str, bytes] = {}
    ctx = {
        "entities": [_entity_context(solution, e) for e in solution.entities],
        **definitions_context(solution),
    }

    def render(rel: str, template: str, header: str = HEADER) -> None:
        body = env.get_template(template).render(**ctx)
        _write(app, f"backend/{rel}", f"{header}\n{body}", files)

    render("manage.py", "manage.py.j2")
    render("requirements.txt", "requirements.txt.j2")
    for name in ("settings", "urls", "wsgi"):
        render(f"config/{name}.py", f"config/{name}.py.j2")
    render("pytest.ini", "pytest.ini.j2")
    for name in ("apps", "models", "admin"):
        render(f"entities/{name}.py", f"entities/{name}.py.j2")
    for rel in LAYER_FILES:
        render(rel, f"{rel}.j2")
    for rel in PACKAGE_MARKERS:
        _write(app, f"backend/{rel}", HEADER + "\n", files)
    _write(app, "backend/config/__init__.py", HEADER + "\n", files)
    _write(app, "backend/entities/__init__.py", HEADER + "\n", files)
    _write(app, "backend/entities/migrations/__init__.py", HEADER + "\n", files)

    migrations = backend / "entities" / "migrations"
    backup = {p: p.read_bytes() for p in migrations.glob("0*.py")}
    for old in backup:
        old.unlink()
    try:
        _makemigrations(backend)
    except BaseException:
        for fresh in migrations.glob("0*.py"):
            fresh.unlink()
        for path, data in backup.items():
            path.write_bytes(data)
        raise
    for path in sorted(migrations.glob("0*.py")):
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        # Django stamps a version/date line; drop it so output is byte-deterministic.
        lines = [ln for ln in lines if not ln.startswith("# Generated by Django")]
        text = "".join(lines).lstrip("\n")
        _write(app, path.relative_to(app).as_posix(), f"{HEADER}\n{text}", files)

    digests = {rel: hashlib.sha256(data).hexdigest() for rel, data in files.items()}
    manifest = json.dumps(digests, indent=2, sort_keys=True) + "\n"
    (app / MANIFEST).write_text(manifest, encoding="utf-8")
    return GenerateResult(written=sorted(files) + [MANIFEST], skipped_ai_owned=[])
