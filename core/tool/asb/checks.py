"""Deterministic static guardrails over a generated app (`asb check`).

Pattern checks (EVAL, RAW_SQL, SECRET, NO_PERMISSION) scan source files of the app.
Only files that are listed in the generator's manifest can be exempted by the pack's
`skip_paths`; AI-written files are always scanned. HEADER_TAMPERED compares
generator-owned files with the sha256 manifest the generator wrote next to the app,
and the manifest itself with an anchor the generator stores outside the app
(`<root>/.asb/manifests/<solution>.sha256`, written by the pack's `generate`, which
is not a tool call and so not reachable by the AI through the hook).
"""

from __future__ import annotations

import ast
import hashlib
import json
import os
import re
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import yaml

from asb.validate import Issue

MANIFEST = ".asb-manifest.json"
GENERATED_MARKER = "GENERATED by asb"
ALLOW_SECRET_MARKER = "asb: allow-secret"
ALL_CHECKS = ("EVAL", "RAW_SQL", "SECRET", "NO_PERMISSION", "HEADER_TAMPERED")
# Policy keys only the core may set: a pack cannot widen what is walked or unscanned.
_CORE_ONLY_KEYS = ("ignore_paths", "build_output")
CORE_POLICY = Path(__file__).resolve().parents[2] / "policy" / "policy.yaml"
# Walked-around directories when the policy has no `ignore_paths`.
_DEFAULT_IGNORE = ["frontend/node_modules/**", ".git/**"]
_PACK_NAME = re.compile(r"[a-z][a-z0-9_-]*")
_SCANNED = {".py", ".ts", ".tsx", ".js", ".jsx", ".json", ".yml", ".yaml"}
_QUOTED_ONLY = {".py", ".ts", ".tsx", ".js", ".jsx", ".json"}

_NAME = r"[\w-]*(?:secret|password|passwd|token|api[_-]?key)[\w-]*"
_SECRET_ASSIGN = re.compile(
    _NAME + r"""["']?\s*(?::\s*[A-Za-z_][\w.\[\], |]*)?\s*[:=]\s*["']([^"']{8,})["']""",
    re.IGNORECASE,
)
_ENV_ASSIGN = re.compile(
    r"""^\s*(?:export\s+|-\s+)?["']?""" + _NAME + r"""["']?\s*[:=]\s*"""
    r"""["']?([^\s"'#]{8,})["']?\s*(?:#.*)?$""",
    re.IGNORECASE,
)
_AWS_KEY = re.compile(r"AKIA[0-9A-Z]{16}")
_PLACEHOLDER = re.compile(r"change-me|example|xxx|<[^>]*>|\$\{[^}]*\}", re.IGNORECASE)
_PLAIN_URL = re.compile(r"https?://[^@]*$", re.IGNORECASE)


def load_policy(root: Path, pack: str | None) -> dict[str, Any]:
    """Core policy merged with the pack's: lists are unioned, packs only tighten
    (they cannot extend `ignore_paths` or `build_output`)."""
    policy = _read_policy(CORE_POLICY)
    if pack is not None:
        if not _PACK_NAME.fullmatch(pack):
            raise ValueError(f"invalid pack name '{pack}'")
        path = Path(root) / "packs" / pack / "policy.yaml"
        pack_policy = {
            k: v for k, v in _read_policy(path).items() if k not in _CORE_ONLY_KEYS
        }
        policy = _merge(policy, pack_policy)
    return policy


def _read_policy(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"policy not found: {path}")
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a mapping")  # noqa: TRY004
    return data


def _merge(core: Any, pack: Any) -> Any:
    if isinstance(core, list) and isinstance(pack, list):
        return core + [x for x in pack if x not in core]
    if isinstance(core, dict) and isinstance(pack, dict):
        out = dict(core)
        for key, value in pack.items():
            out[key] = _merge(core[key], value) if key in core else value
        return out
    return core  # the core value always wins; a pack cannot override it


def anchor_path(root: Path, solution: str) -> Path:
    return Path(root) / ".asb" / "manifests" / f"{solution}.sha256"


def write_anchor(root: Path, solution: str, app_dir: Path) -> None:
    """Record the sha256 of the app's manifest outside the app (generator side)."""
    digest = hashlib.sha256((Path(app_dir) / MANIFEST).read_bytes()).hexdigest()
    path = anchor_path(root, solution)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(digest + "\n", encoding="utf-8")


def read_anchor(root: Path, solution: str) -> str | None:
    try:
        text = anchor_path(root, solution).read_text(encoding="utf-8").strip()
    except (OSError, UnicodeDecodeError):
        return None
    return text or None


def _glob(pattern: str) -> re.Pattern[str]:
    out: list[str] = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out))


def _matches(patterns: list[re.Pattern[str]], rel: str) -> bool:
    return any(p.fullmatch(rel) for p in patterns)


def _walk(
    app_dir: Path, ignore: list[re.Pattern[str]]
) -> Iterator[tuple[Path, str, bool]]:
    """(path, relative posix path, is_symlink) for files and symlinks, pruning `ignore`."""
    for dirpath, dirnames, filenames in os.walk(app_dir):
        base = Path(dirpath)
        rel_dir = base.relative_to(app_dir).as_posix()
        prefix = "" if rel_dir == "." else rel_dir + "/"
        keep = []
        for d in sorted(dirnames):
            # A dummy child tells whether a pattern such as "x/**" covers the directory.
            if d == "__pycache__" or _matches(ignore, f"{prefix}{d}/_"):
                continue
            if (base / d).is_symlink():
                yield base / d, prefix + d, True
                continue
            keep.append(d)
        dirnames[:] = keep
        for name in sorted(filenames):
            path = base / name
            rel = prefix + name
            if not _matches(ignore, rel):
                yield path, rel, path.is_symlink()


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _sha256(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def _is_env_file(name: str) -> bool:
    return name.startswith(".env") and name != ".env.example"


# --- individual checks -------------------------------------------------------------

_DANGEROUS_BUILTINS = ("eval", "exec", "compile")


def _module_bindings(tree: ast.Module) -> tuple[set[str], dict[str, str], set[str]]:
    """Module-level bindings: (shadowing names, aliases of builtins, builtins-module names).

    Only module-level statements count (not names bound inside functions or classes).
    Importing from or aliasing the `builtins` module does not shadow the builtins.
    """
    shadow: set[str] = set()
    aliases: dict[str, str] = {}
    modules = {"builtins", "__builtins__"}

    def visit(body: list[ast.stmt]) -> None:
        for node in body:
            if isinstance(node, ast.Import):
                for alias in node.names:
                    bound = (alias.asname or alias.name).split(".")[0]
                    if alias.name == "builtins":
                        modules.add(bound)
                    else:
                        shadow.add(bound)
            elif isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    bound = alias.asname or alias.name
                    if node.module == "builtins" and node.level == 0:
                        if alias.name in _DANGEROUS_BUILTINS:
                            aliases[bound] = alias.name
                    else:
                        shadow.add(bound)
            elif isinstance(
                node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
            ):
                shadow.add(node.name)
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = (
                    node.targets if isinstance(node, ast.Assign) else [node.target]
                )
                shadow.update(t.id for t in targets if isinstance(t, ast.Name))
            elif isinstance(node, ast.If | ast.With | ast.AsyncWith):
                visit(node.body)
                visit(getattr(node, "orelse", []))
            elif isinstance(node, ast.Try):
                visit(node.body)
                visit(node.orelse)
                visit(node.finalbody)
                for handler in node.handlers:
                    visit(handler.body)

    visit(tree.body)
    return shadow, aliases, modules


def _eval_issues(tree: ast.Module, rel: str) -> list[tuple[int, Issue]]:
    shadowed, aliases, modules = _module_bindings(tree)
    out = []

    def add(node: ast.AST, what: str) -> None:
        line = getattr(node, "lineno", 0)
        out.append((line, Issue("EVAL", rel, f"line {line}: use of {what}")))

    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Name)
            and isinstance(node.ctx, ast.Load)
            and node.id not in shadowed
        ):
            if node.id in _DANGEROUS_BUILTINS:
                add(node, f"{node.id}()")
            elif node.id in aliases:
                add(node, f"{aliases[node.id]}() (as {node.id})")
        elif (
            isinstance(node, ast.Attribute)
            and node.attr in _DANGEROUS_BUILTINS
            and isinstance(node.value, ast.Name)
            and node.value.id in modules
        ):
            add(node, f"builtins.{node.attr}()")
    return out


def _is_const(node: ast.expr) -> bool:
    if isinstance(node, ast.Constant):
        return True
    if isinstance(node, ast.JoinedStr):
        return not any(isinstance(v, ast.FormattedValue) for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Mod, ast.Add)):
        return _is_const(node.left) and _is_const(node.right)
    return False


def _is_formatted(node: ast.expr) -> bool:
    if isinstance(node, ast.JoinedStr):
        return not _is_const(node)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Mod, ast.Add)):
        return not _is_const(node)
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "format"
    )


def _formatted_names(tree: ast.AST) -> set[str]:
    """Variables assigned a formatted string somewhere in the module."""
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and _is_formatted(node.value):
            names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        elif (
            isinstance(node, ast.AnnAssign)
            and node.value is not None
            and isinstance(node.target, ast.Name)
            and _is_formatted(node.value)
        ):
            names.add(node.target.id)
    return names


def _sql_candidates(node: ast.Call) -> list[ast.expr]:
    found = list(node.args[:1]) + [
        k.value
        for k in node.keywords
        if k.arg in ("sql", "query", "where", "tables", "order_by")
    ]
    flat: list[ast.expr] = []
    for item in found:
        if isinstance(item, (ast.List, ast.Tuple)):
            flat.extend(item.elts)
        else:
            flat.append(item)
    return flat


def _raw_sql_issues(tree: ast.AST, rel: str) -> list[tuple[int, Issue]]:
    tainted = _formatted_names(tree)
    out = []
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr in ("raw", "execute", "extra")
        ):
            continue
        if any(
            _is_formatted(a) or (isinstance(a, ast.Name) and a.id in tainted)
            for a in _sql_candidates(node)
        ):
            out.append(
                (
                    node.lineno,
                    Issue(
                        "RAW_SQL",
                        rel,
                        f"line {node.lineno}: .{node.func.attr}() with formatted SQL; "
                        "pass parameters separately",
                    ),
                )
            )
    return out


def _base_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _defines(body: list[ast.stmt], attribute: str) -> bool:
    for stmt in body:
        if isinstance(stmt, ast.Assign):
            if any(isinstance(t, ast.Name) and t.id == attribute for t in stmt.targets):
                return True
        elif (
            (
                isinstance(stmt, ast.AnnAssign)
                and isinstance(stmt.target, ast.Name)
                and stmt.target.id == attribute
                and stmt.value is not None
            )
            or isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef))
            and (stmt.name == "get_permissions")
        ):
            return True
    return False


def _permission_issues(
    tree: ast.AST, rel: str, bases: set[str], attribute: str
) -> list[tuple[int, Issue]]:
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        if not any(_base_name(b) in bases for b in node.bases):
            continue
        if not _defines(node.body, attribute):
            out.append(
                (
                    node.lineno,
                    Issue(
                        "NO_PERMISSION",
                        rel,
                        f"line {node.lineno}: class '{node.name}' does not set "
                        f"'{attribute}'",
                    ),
                )
            )
    return out


def _secret_value_ok(value: str) -> bool:
    return bool(_PLACEHOLDER.search(value) or _PLAIN_URL.fullmatch(value))


def _secret_issues(
    text: str, rel: str, unquoted: bool, marker_ok: bool
) -> list[tuple[int, Issue]]:
    out = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        what = None
        if _AWS_KEY.search(line):
            what = "AWS-style access key"  # never exempted by the marker
        elif not (marker_ok and ALLOW_SECRET_MARKER in line):
            if unquoted:
                matches = [m for m in [_ENV_ASSIGN.match(line)] if m]
            else:
                matches = list(_SECRET_ASSIGN.finditer(line))
            if any(not _secret_value_ok(m.group(1)) for m in matches):
                what = "hard-coded secret literal"
        if what:
            out.append((lineno, Issue("SECRET", rel, f"line {lineno}: {what}")))
    return out


def _load_manifest(app_dir: Path) -> tuple[dict[str, Any] | None, list[Issue]]:
    """(manifest or None, issues about the manifest file itself)."""
    path = app_dir / MANIFEST
    if not path.is_file():
        return None, [
            Issue(
                "HEADER_TAMPERED", MANIFEST, "manifest missing: app was not generated"
            )
        ]
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise ValueError("expected an object")  # noqa: TRY004
    except (OSError, ValueError) as exc:
        return None, [Issue("HEADER_TAMPERED", MANIFEST, f"manifest unreadable: {exc}")]
    return data, []


def _pattern_checks(
    app_dir: Path,
    policy: dict[str, Any],
    enabled: set[str],
    manifest: dict[str, Any],
    entries: list[tuple[Path, str, bool]],
) -> list[Issue]:
    skip = [_glob(p) for p in policy.get("skip_paths", [])]
    build = [_glob(p) for p in policy.get("build_output", [])]
    perm = policy.get("no_permission") or {}
    bases = set(perm.get("base_classes") or [])
    attribute = perm.get("attribute")
    issues: list[Issue] = []
    for path, rel, is_link in entries:
        if is_link:
            issues.append(
                Issue("SYMLINK", rel, "symlinks are not allowed inside the app")
            )
            continue
        suffix = path.suffix
        env_file = _is_env_file(path.name)
        if rel == MANIFEST or (suffix not in _SCANNED and not env_file):
            continue
        listed = isinstance(manifest.get(rel), str)
        if listed and _matches(skip, rel):
            continue  # generator-owned exemption (vendored code, migrations)
        if not listed and suffix != ".py" and _matches(build, rel):
            continue  # built output such as a bundle
        text = _read(path)
        if text is None:
            continue
        found: list[tuple[int, Issue]] = []
        if suffix == ".py":
            try:
                tree: ast.Module | None = ast.parse(text, filename=rel)
            except (SyntaxError, ValueError) as exc:
                issues.append(Issue("PARSE_ERROR", rel, f"cannot parse: {exc}"))
                tree = None
            if tree is not None:
                if "EVAL" in enabled:
                    found += _eval_issues(tree, rel)
                if "RAW_SQL" in enabled:
                    found += _raw_sql_issues(tree, rel)
                if "NO_PERMISSION" in enabled and bases and attribute:
                    found += _permission_issues(tree, rel, bases, attribute)
        if "SECRET" in enabled:
            marker_ok = (
                ALLOW_SECRET_MARKER in text
                and listed
                and _sha256(path) == manifest.get(rel)
            )
            found += _secret_issues(
                text, rel, env_file or suffix not in _QUOTED_ONLY, marker_ok
            )
        issues += [i for _, i in sorted(found, key=lambda t: t[0])]
    return issues


def _first_line(path: Path) -> str:
    try:
        with path.open("rb") as fh:
            return fh.readline(512).decode("utf-8", errors="ignore")
    except OSError:
        return ""


def _tamper_issues(
    app_dir: Path,
    manifest: dict[str, Any],
    entries: list[tuple[Path, str, bool]],
    anchor: str | None,
) -> list[Issue]:
    issues: list[Issue] = []
    if (
        anchor is not None
        and (app_dir / MANIFEST).is_file()
        and _sha256(app_dir / MANIFEST) != anchor
    ):
        issues.append(
            Issue(
                "HEADER_TAMPERED",
                MANIFEST,
                "manifest edited: differs from the generator's anchor",
            )
        )
    root = app_dir.resolve()
    for rel, digest in sorted(manifest.items()):
        target = (app_dir / rel).resolve()
        if (
            not isinstance(digest, str)
            or Path(rel).is_absolute()
            or not target.is_relative_to(root)
        ):
            issues.append(Issue("HEADER_TAMPERED", rel, "invalid manifest entry"))
            continue
        path = app_dir / rel
        if not path.is_file() and not path.is_symlink():
            issues.append(
                Issue("HEADER_TAMPERED", rel, "missing: generated file was removed")
            )
        elif path.is_symlink() or _sha256(path) != digest:
            issues.append(
                Issue(
                    "HEADER_TAMPERED",
                    rel,
                    "edited: content differs from generation; regenerate instead",
                )
            )
    for path, rel, is_link in entries:
        if is_link or rel in manifest or rel == MANIFEST:
            continue
        if path.name == "conftest.py" and rel.startswith("backend/"):
            issues.append(
                Issue(
                    "UNLISTED_CONFTEST",
                    rel,
                    "conftest.py is not in the manifest: it could change what the "
                    "tests collect or assert",
                )
            )
        if GENERATED_MARKER in _first_line(path):
            issues.append(
                Issue(
                    "HEADER_TAMPERED",
                    rel,
                    "unknown generated file: carries the generated header "
                    "but is not in the manifest",
                )
            )
    return issues


def run_checks(
    app_dir: Path, policy: dict[str, Any], anchor: str | None = None
) -> list[Issue]:
    """Run the enabled checks over `app_dir`; issue paths are relative to it.

    `anchor` is the generator's recorded sha256 of the manifest (see `read_anchor`).
    """
    app_dir = Path(app_dir)
    enabled = set(policy.get("checks", ALL_CHECKS))
    ignore = [_glob(p) for p in policy.get("ignore_paths", _DEFAULT_IGNORE)]
    entries = list(_walk(app_dir, ignore))
    manifest, manifest_issues = _load_manifest(app_dir)
    issues = _pattern_checks(app_dir, policy, enabled, manifest or {}, entries)
    if "HEADER_TAMPERED" in enabled:
        issues += manifest_issues
        issues += _tamper_issues(app_dir, manifest or {}, entries, anchor)
    return issues
