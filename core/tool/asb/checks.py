"""Deterministic static guardrails over a generated app (`asb check`).

Pattern checks (EVAL, RAW_SQL, SECRET, NO_PERMISSION) scan source files that are not
excluded by the policy's `skip_paths`. HEADER_TAMPERED compares generator-owned files
with the sha256 manifest the generator wrote next to the app.
"""

from __future__ import annotations

import ast
import hashlib
import json
import os
import re
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import yaml

from asb.validate import Issue

MANIFEST = ".asb-manifest.json"
GENERATED_MARKER = "GENERATED by asb"
ALLOW_SECRET_MARKER = "asb: allow-secret"
ALL_CHECKS = ("EVAL", "RAW_SQL", "SECRET", "NO_PERMISSION", "HEADER_TAMPERED")
CORE_POLICY = Path(__file__).resolve().parents[2] / "policy" / "policy.yaml"
# Directories never worth walking when looking for generated files.
_JUNK_DIRS = {".git", "node_modules", "dist", "__pycache__"}
_PACK_NAME = re.compile(r"[a-z][a-z0-9_-]*")

_SECRET_NAMES = r"(?:api[_-]?secret|api[_-]?key|password|passwd|secret[_-]?key|token)"
_SECRET_ASSIGN = re.compile(
    _SECRET_NAMES + r"""["']?\s*[:=]\s*["']([^"']{8,})["']""", re.IGNORECASE
)
_ENV_ASSIGN = re.compile(
    r"""^\s*(?:export\s+)?[A-Za-z0-9_.-]*""" + _SECRET_NAMES + r"""[A-Za-z0-9_.-]*"""
    r"""\s*=\s*["']?([^\s"']{8,})["']?\s*$""",
    re.IGNORECASE,
)
_AWS_KEY = re.compile(r"AKIA[0-9A-Z]{16}")
_PLACEHOLDER = re.compile(r"change-me|example|xxx|<[^>]*>|\$\{[^}]*\}", re.IGNORECASE)


def load_policy(root: Path, pack: str | None) -> dict[str, Any]:
    """Core policy merged with the pack's: lists are unioned, packs only tighten."""
    policy = _read_policy(CORE_POLICY, required=True)
    if pack is not None:
        if not _PACK_NAME.fullmatch(pack):
            raise ValueError(f"invalid pack name '{pack}'")
        extra = _read_policy(Path(root) / "packs" / pack / "policy.yaml")
        policy = _merge(policy, extra)
    return policy


def _read_policy(path: Path, required: bool = False) -> dict[str, Any]:
    if not path.is_file():
        if required:
            raise FileNotFoundError(f"core policy not found: {path}")
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a mapping")  # noqa: TRY004
    return data


def _merge(core: Any, pack: Any) -> Any:
    if isinstance(core, list) and isinstance(pack, list):
        return core + [x for x in pack if x not in core]
    if isinstance(core, dict) and isinstance(pack, dict):
        out = dict(core)
        for key, value in pack.items():
            out[key] = _merge(core[key], value) if key in core else value
        return out
    return core  # the core value always wins; a pack cannot override it


def _glob(pattern: str) -> re.Pattern[str]:
    out: list[str] = []
    i = 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out))


def _iter_files(
    app_dir: Path, skip: list[re.Pattern[str]]
) -> Iterator[tuple[Path, str]]:
    """(path, app-relative posix path) of non-symlink files not matched by `skip`."""
    for dirpath, dirnames, filenames in os.walk(app_dir):
        base = Path(dirpath)
        rel_dir = base.relative_to(app_dir).as_posix()
        prefix = "" if rel_dir == "." else rel_dir + "/"
        # A dummy child tells whether a pattern such as "x/**" covers the directory.
        dirnames[:] = sorted(
            d for d in dirnames if not any(p.fullmatch(f"{prefix}{d}/_") for p in skip)
        )
        for name in sorted(filenames):
            path = base / name
            rel = prefix + name
            if path.is_symlink() or any(p.fullmatch(rel) for p in skip):
                continue
            yield path, rel


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _is_env_file(name: str) -> bool:
    return name.startswith(".env") and name != ".env.example"


# --- individual checks -------------------------------------------------------------


def _eval_issues(tree: ast.AST, rel: str) -> list[tuple[int, Issue]]:
    out = []
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name)
            and node.func.id in ("eval", "exec", "compile")
        ):
            out.append(
                (
                    node.lineno,
                    Issue("EVAL", rel, f"line {node.lineno}: call to {node.func.id}()"),
                )
            )
    return out


def _is_formatted(node: ast.expr) -> bool:
    if isinstance(node, ast.JoinedStr):
        return any(isinstance(v, ast.FormattedValue) for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Mod, ast.Add)):
        return not (
            isinstance(node.left, ast.Constant) and isinstance(node.right, ast.Constant)
        )
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == "format"
    )


def _raw_sql_issues(tree: ast.AST, rel: str) -> list[tuple[int, Issue]]:
    out = []
    for node in ast.walk(tree):
        if not (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr in ("raw", "execute", "extra")
        ):
            continue
        args = list(node.args[:1]) + [
            k.value for k in node.keywords if k.arg in ("sql", "query")
        ]
        if any(_is_formatted(a) for a in args):
            out.append(
                (
                    node.lineno,
                    Issue(
                        "RAW_SQL",
                        rel,
                        f"line {node.lineno}: .{node.func.attr}() with formatted SQL; "
                        "pass parameters separately",
                    ),
                )
            )
    return out


def _base_name(node: ast.expr) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _assigns(body: list[ast.stmt], attribute: str) -> bool:
    for stmt in body:
        if isinstance(stmt, ast.Assign):
            if any(isinstance(t, ast.Name) and t.id == attribute for t in stmt.targets):
                return True
        elif (
            isinstance(stmt, ast.AnnAssign)
            and isinstance(stmt.target, ast.Name)
            and stmt.target.id == attribute
            and stmt.value is not None
        ):
            return True
    return False


def _permission_issues(
    tree: ast.AST, rel: str, bases: set[str], attribute: str
) -> list[tuple[int, Issue]]:
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        if not any(_base_name(b) in bases for b in node.bases):
            continue
        if not _assigns(node.body, attribute):
            out.append(
                (
                    node.lineno,
                    Issue(
                        "NO_PERMISSION",
                        rel,
                        f"line {node.lineno}: class '{node.name}' does not set "
                        f"'{attribute}'",
                    ),
                )
            )
    return out


def _secret_issues(text: str, rel: str, env_file: bool) -> list[tuple[int, Issue]]:
    out = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        if ALLOW_SECRET_MARKER in line:
            continue
        what = None
        if _AWS_KEY.search(line):
            what = "AWS-style access key"
        elif env_file:
            m = _ENV_ASSIGN.match(line)
            if m and not _PLACEHOLDER.search(m.group(1)):
                what = "hard-coded secret value"
        else:
            for m in _SECRET_ASSIGN.finditer(line):
                if not _PLACEHOLDER.search(m.group(1)):
                    what = "hard-coded secret literal"
                    break
        if what:
            out.append((lineno, Issue("SECRET", rel, f"line {lineno}: {what}")))
    return out


def _pattern_checks(
    app_dir: Path, policy: dict[str, Any], enabled: set[str]
) -> list[Issue]:
    skip = [_glob(p) for p in policy.get("skip_paths", [])]
    perm = policy.get("no_permission") or {}
    bases = set(perm.get("base_classes") or [])
    attribute = perm.get("attribute")
    issues: list[Issue] = []
    for path, rel in _iter_files(app_dir, skip):
        suffix = path.suffix
        env_file = _is_env_file(path.name)
        if suffix not in (".py", ".ts", ".tsx") and not env_file:
            continue
        text = _read(path)
        if text is None:
            continue
        found: list[tuple[int, Issue]] = []
        if suffix == ".py":
            try:
                tree = ast.parse(text, filename=rel)
            except (SyntaxError, ValueError) as exc:
                issues.append(Issue("PARSE_ERROR", rel, f"cannot parse: {exc}"))
                tree = None
            if tree is not None:
                if "EVAL" in enabled:
                    found += _eval_issues(tree, rel)
                if "RAW_SQL" in enabled:
                    found += _raw_sql_issues(tree, rel)
                if "NO_PERMISSION" in enabled and bases and attribute:
                    found += _permission_issues(tree, rel, bases, attribute)
        if "SECRET" in enabled:
            found += _secret_issues(text, rel, env_file)
        issues += [i for _, i in sorted(found, key=lambda t: t[0])]
    return issues


def _sha256(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def _first_line(path: Path) -> str:
    try:
        with path.open("rb") as fh:
            return fh.readline(512).decode("utf-8", errors="ignore")
    except OSError:
        return ""


def _tamper_issues(app_dir: Path) -> list[Issue]:
    issues: list[Issue] = []
    manifest: dict[str, Any] = {}
    manifest_path = app_dir / MANIFEST
    if manifest_path.is_file():
        try:
            data = json.loads(manifest_path.read_text(encoding="utf-8"))
            if not isinstance(data, dict):
                raise ValueError("expected an object")  # noqa: TRY004
            manifest = data
        except (OSError, ValueError) as exc:
            issues.append(
                Issue("HEADER_TAMPERED", MANIFEST, f"manifest unreadable: {exc}")
            )
    root = app_dir.resolve()
    for rel, digest in sorted(manifest.items()):
        target = (app_dir / rel).resolve() if isinstance(rel, str) else None
        if (
            target is None
            or not isinstance(digest, str)
            or Path(rel).is_absolute()
            or not target.is_relative_to(root)
        ):
            issues.append(Issue("HEADER_TAMPERED", str(rel), "invalid manifest entry"))
            continue
        path = app_dir / rel
        if not path.is_file() and not path.is_symlink():
            issues.append(
                Issue("HEADER_TAMPERED", rel, "missing: generated file was removed")
            )
        elif path.is_symlink() or _sha256(path) != digest:
            issues.append(
                Issue(
                    "HEADER_TAMPERED",
                    rel,
                    "edited: content differs from generation; regenerate instead",
                )
            )
    known = set(manifest)
    junk = [_glob(f"**/{d}/**") for d in sorted(_JUNK_DIRS)]
    for path, rel in _iter_files(app_dir, junk):
        if rel in known or rel == MANIFEST:
            continue
        if GENERATED_MARKER in _first_line(path):
            issues.append(
                Issue(
                    "HEADER_TAMPERED",
                    rel,
                    "unknown generated file: carries the generated header "
                    "but is not in the manifest",
                )
            )
    return issues


def run_checks(app_dir: Path, policy: dict[str, Any]) -> list[Issue]:
    """Run the enabled checks over `app_dir`; issue paths are relative to it."""
    app_dir = Path(app_dir)
    enabled = set(policy.get("checks", ALL_CHECKS))
    issues = _pattern_checks(app_dir, policy, enabled)
    if "HEADER_TAMPERED" in enabled:
        issues += _tamper_issues(app_dir)
    return issues
